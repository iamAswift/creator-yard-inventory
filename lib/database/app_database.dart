class AppDatabase extends _$AppDatabase {
  AppDatabase() : super(_openConnection());

  @override
  int get schemaVersion => 26; // bump version when schema changes

  @override
  MigrationStrategy get migration => MigrationStrategy(
    onCreate: (m) async {
      await m.createAll(); // create all tables on fresh install
    },
    onUpgrade: (m, from, to) async {
      if (from <= 1) {
        // upgrading from schema v1 → v2
        await m.createTable(products);
      }
      if (from <= 2) {
        // upgrading from schema v2 → v3
        await m.createTable(stockMovements);
      }
      if (from <= 3) {
        // upgrading from schema v3 → v4
        await m.createTable(suppliers);
      }
      if (from <= 4) {
        // upgrading from schema v4 → v5
        await m.createTable(sales);
      }

      if (from <= 5) {
        await m.addColumn(sales, sales.paymentMethod);
        await m.addColumn(sales, sales.cashAmount);
        await m.addColumn(sales, sales.transferAmount);
      }

      if (from <= 6) {
        await m.addColumn(products, products.stock); // ✅ new stock column
      }

      if (from <= 7) {
        // upgrading from schema v5 → v6
        await m.createTable(settings);
      }

      if (from <= 8) {
        await m.createTable(categories);
      }

      if (from <= 10) {
        await m.addColumn(sales, sales.staffId);
      }

      if (from <= 11) {
        await m.createTable(userProfiles);
      }

      if (from <= 15) {
        await customStatement('''
              UPDATE sales
              SET cost_price_at_sale = (
                SELECT cost_price
                FROM products
                WHERE products.id = sales.product_id
              )
              WHERE cost_price_at_sale = 0
            ''');
      }

      // Schema 16 → 17
      if (from <= 16) {
        await m.addColumn(users, users.loginId);

        // Give existing users a login ID based on their existing ID.
        await customStatement('''
            UPDATE users
            SET login_id = 'USER' || printf('%04d', id)
            WHERE login_id IS NULL
          ''');
      }

      if (from <= 17) {
        await m.addColumn(users, users.isActive);
      }

      if (from <= 18) {
        await m.createTable(attendance);
      }

      // v19 → v20
      if (from <= 19) {
        await m.addColumn(attendance, attendance.correctedByUserId);

        await m.addColumn(attendance, attendance.correctedAt);

        await m.addColumn(attendance, attendance.correctionNote);
      }

      // SCHEMA 20 → 21 // STAFF PURCHASES
      if (from <= 20) {
        await m.createTable(staffPurchases);
      }

      // SCHEMA 21 → 22 // STAFF PURCHASES
      if (from <= 21) {
        await m.createTable(staffDebtPayments);
      }

      // ============================================================
      // SCHEMA 22 → 23
      // SUPPLIER PAYABLES
      // ============================================================

      if (from <= 22) {
        // Supplier deliveries must exist before delivery items
        // because delivery items reference supplier deliveries.
        await m.createTable(supplierDeliveries);

        // Individual products received in each delivery.
        await m.createTable(supplierDeliveryItems);

        // Actual payments made to suppliers.
        await m.createTable(supplierPayments);

        // Connect payments to one or more supplier deliveries.
        await m.createTable(supplierPaymentAllocations);
      }

      // SCHEMA 23 → 24
      // LINK STOCK MOVEMENTS TO SUPPLIER DELIVERIES

      if (from <= 23) {
        await m.addColumn(stockMovements, stockMovements.deliveryId);
      }

      if (from <= 24) {
        await m.createTable(saleEmailQueues);
      }

      // SCHEMA 25 → 26
      // SYSTEM STOCK VERIFICATION / CLOSING

      if (from <= 25) {
        // Parent verification record must exist before its items.
        await m.createTable(stockVerifications);

        // Individual product counts reference stockVerifications.
        await m.createTable(stockVerificationItems);
      }

      // if you add more versions later, handle them here
    },
  );
}

